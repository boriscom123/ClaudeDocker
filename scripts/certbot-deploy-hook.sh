#!/bin/sh
# Перезагрузка общего nginx после обновления сертификата.
#
# Задача: certbot обновляет файлы в /etc/letsencrypt, но nginx читает
# сертификат один раз при старте — без перезагрузки он до конца жизни
# контейнера отдаёт старый, уже просроченный. Симптом появляется через 60+
# дней после установки и выглядит как внезапно сломавшийся у всех сайт.
#
# Вызывается certbot'ом из /etc/letsencrypt/renewal-hooks/deploy/ после
# каждого успешного обновления любого сертификата. Установка — см. README.
set -eu

NGINX_CONTAINER=shared-nginx-1

# Контейнера может не быть: слой временно опущен или переименован. Это не
# повод завалить обновление сертификата — оно уже прошло успешно.
if ! docker ps --format '{{.Names}}' | grep -qx "$NGINX_CONTAINER"; then
  echo "certbot-deploy-hook: контейнер $NGINX_CONTAINER не запущен, перезагрузка пропущена"
  exit 0
fi

# Мягкая перезагрузка: старые соединения дорабатываются, новые уже с новым
# сертификатом. Рестарт контейнера здесь был бы грубее и с простоем.
docker exec "$NGINX_CONTAINER" nginx -s reload
echo "certbot-deploy-hook: $NGINX_CONTAINER перезагружен с обновлённым сертификатом"
